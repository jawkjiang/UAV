print("\n理论分析:")
print("""
1. 训练集类别分布对模型的影响:
   - 训练集攻击60% → 模型学习到"攻击是常见的"
   - 决策边界会向"容易预测为攻击"的方向偏移
   - 在正常样本占97%的测试集上 → 大量误报

2. 为什么降低训练集攻击比例可能有效:
   ✓ 让模型学习到"正常是主流"的先验分布
   ✓ 决策边界会更保守，不轻易判定为攻击
   ✓ 减少对攻击特征的过拟合
   
3. 但可能带来的问题:
   ✗ TPR可能下降（从99.05%降低）
   ✗ 攻击样本过少，模型学习不充分
   ✗ 某些攻击类型样本不足
""")

print("\n实验建议:")
print("""
方案A：匹配测试集分布
  - 训练集攻击比例: 3-5% (匹配测试集)
  - 预期: FPR大幅下降，TPR可能轻微下降
  - 风险: 攻击样本绝对数量少，难以学习
  
方案B：中等比例
  - 训练集攻击比例: 20-30%
  - 预期: FPR下降，TPR基本保持
  - 平衡: 既有足够攻击样本，又不过度偏向攻击
  
方案C：分层采样 + 类别权重
  - 保持攻击样本数量不变
  - 增加正常样本（5-10倍）
  - 使用class_weight平衡损失函数
  - 预期: 最好的效果
""")

